const dict: Record<Locale, Record<TKey, string>> = { zh, en }

type Ctx = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (k: TKey, vars?: Record<string, string | number>) => string
}

const LocaleContext = createContext<Ctx>({
  locale: 'zh',
  setLocale: () => undefined,
  t: (k) => zh[k],
})

function readLocale(): Locale {
  const v = localStorage.getItem(STORAGE_KEY)
  return v === 'en' ? 'en' : 'zh'
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale)

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l)
    localStorage.setItem(STORAGE_KEY, l)
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'
  }, [locale])

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (k: TKey, vars?: Record<string, string | number>) => {
        // 非字典 key（TRIMP/rTSS 等专有名词）原样透传
        let str = dict[locale][k] ?? zh[k] ?? String(k)
        if (vars) {
          for (const [name, v] of Object.entries(vars)) str = str.replaceAll(`{${name}}`, String(v))
        }
        return str
      },
    }),
    [locale, setLocale],
  )
  // .ts 文件不带 JSX；provider 用 createElement（react-refresh 只允许组件文件导出组件）
  return createElement(LocaleContext.Provider, { value }, children)
}

export function useLocale(): Ctx {
  return useContext(LocaleContext)
}

